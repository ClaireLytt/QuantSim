function t(key, ...args) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.zh[key] ?? key;
  args.forEach((a, i) => { s = s.replaceAll(`{${i}}`, a); });
  return s;
}

// 双语内容对象 (如题库) 取当前语言分支
function pick(obj) {
  return obj[LANG] ?? obj.zh;
}

