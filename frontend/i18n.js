const I18N = { zh: {}, en: {} };
for (const k in PAIRS) { I18N.zh[k] = PAIRS[k][0]; I18N.en[k] = PAIRS[k][1]; }

let LANG = "zh";
try {
  const saved = localStorage.getItem("qs_lang");
  if (saved === "en" || saved === "zh") LANG = saved;
} catch (e) { /* 隐私模式下忽略 */ }

function t(key, ...args) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.zh[key] ?? key;
  // 替换值用函数形式: 字符串第二参会解析 $&/$' 等替换模式, 用户名含 $ 时文案错乱
  args.forEach((a, i) => { s = s.replaceAll(`{${i}}`, () => String(a)); });
  return s;
}

